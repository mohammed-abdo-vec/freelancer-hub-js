#!/usr/bin/env python3
"""Regenerate README.md (board index) and board.csv (Jira/Trello import) from story frontmatter.

Usage: python3 stories/build-board.py
Run it after adding a story or changing a `status:`.
"""
import csv
import re
from pathlib import Path

HERE = Path(__file__).parent

# Build order: milestones roughly follow SPEC.md §8 phases. Order inside a milestone = suggested order.
MILESTONES = [
    ('M1 · Foundation', ['FND-1', 'FND-2', 'FND-3', 'FND-4', 'FND-5']),
    ('M2 · Authentication', ['AUTH-1', 'AUTH-2', 'AUTH-6', 'AUTH-3', 'AUTH-4', 'AUTH-5']),
    ('M3 · Providers', ['PROV-1', 'PROV-2', 'PROV-3', 'PROV-4', 'PROV-5', 'PROV-6']),
    ('M4 · Chat: read & organize', ['CHAT-7', 'CHAT-14', 'CHAT-4', 'CHAT-5', 'CHAT-13', 'CHAT-8', 'CHAT-9']),
    ('M5 · Chat: send & stream', ['CHAT-2', 'CHAT-10', 'CHAT-3', 'CHAT-11', 'CHAT-1', 'CHAT-6', 'CHAT-12']),
    ('M6 · Compare', ['CMP-1', 'CMP-2', 'CMP-3']),
    ('M7 · Dashboard & settings', ['DASH-1', 'DASH-2', 'DASH-3', 'DASH-4', 'DASH-5', 'SET-1', 'SET-2', 'SET-3', 'SET-4']),
    ('M8 · Quality & release', ['QA-1', 'QA-2', 'QA-3']),
]


def parse(path: Path):
    text = path.read_text()
    m = re.match(r'^---\n(.*?)\n---\n(.*)$', text, re.S)
    if not m:
        raise SystemExit(f'{path.name}: missing frontmatter')
    meta = {}
    for line in m.group(1).splitlines():
        key, _, value = line.partition(':')
        value = value.split('#')[0].strip()
        if value.startswith('['):
            value = [v.strip() for v in value.strip('[]').split(',') if v.strip()]
        meta[key.strip()] = value
    meta['file'] = path.name
    meta['body'] = m.group(2).strip()
    return meta


stories = {s['id']: s for s in (parse(p) for p in sorted(HERE.glob('*.md')) if p.name not in ('README.md', '_TEMPLATE.md'))}

# Sanity checks: every story is scheduled once, deps exist and come earlier in the build order.
order = [sid for _, ids in MILESTONES for sid in ids]
assert sorted(order) == sorted(stories), f'unscheduled or unknown: {set(order) ^ set(stories)}'
position = {sid: i for i, sid in enumerate(order)}
for sid, s in stories.items():
    for dep in s['depends_on']:
        assert dep in stories, f'{sid} depends on unknown {dep}'
        assert position[dep] < position[sid], f'{sid} is scheduled before its dependency {dep}'
    spec = (HERE / s['spec']).resolve()
    assert spec.exists(), f'{sid}: spec not found at {s["spec"]}'

milestone_of = {sid: name for name, ids in MILESTONES for sid in ids}

# ── README.md ─────────────────────────────────────────────
total = sum(int(s['points']) for s in stories.values())
done = sum(int(s['points']) for s in stories.values() if s['status'] == 'Done')
lines = [
    '# AI Hub · Story board',
    '',
    '<!-- Generated by build-board.py. Edit the story files, then run `python3 stories/build-board.py`. -->',
    '',
    'One file per story, ready to copy into Jira, Trello, Linear or GitHub Projects. Each card links to its '
    'AI-ready handover in [`../implementation-specs/`](../implementation-specs/).',
    '',
    f'**{len(stories)} stories · {total} points · {done} done.** Build top to bottom: every story only depends on '
    'stories above it.',
    '',
    '| Field | Meaning |',
    '|---|---|',
    '| `type` | **Story** = user-facing value · **Task** = technical enabler |',
    '| `priority` | Highest → Low (Jira scale) |',
    '| `points` | Fibonacci estimate (1 = under an hour with AI, 8 = a full session) |',
    '| `status` | To Do · In Progress · In Review · Done |',
    '| `depends_on` | Finish these first |',
    '',
    '**Import:** [`board.csv`](board.csv) works with Jira (*System → External system import → CSV*) and Trello '
    '(via a CSV import Power-Up, or copy cards by hand). Stories marked "Added story" aren\'t in SPEC.md §2 '
    'but are needed to deliver it.',
    '',
]
for name, ids in MILESTONES:
    pts = sum(int(stories[i]['points']) for i in ids)
    lines += [f'## {name} ({pts} pts)', '', '| ID | Story | Type | Priority | Pts | Depends on | Status |', '|---|---|---|---|---|---|---|']
    for sid in ids:
        s = stories[sid]
        deps = ', '.join(s['depends_on']) or '—'
        lines.append(
            f"| [{sid}]({s['file']}) | {s['title']} | {s['type']} | {s['priority']} | {s['points']} | {deps} | {s['status']} |"
        )
    lines.append('')
(HERE / 'README.md').write_text('\n'.join(lines))

# ── board.csv ─────────────────────────────────────────────
with open(HERE / 'board.csv', 'w', newline='') as f:
    w = csv.writer(f)
    w.writerow(['Issue ID', 'Summary', 'Issue Type', 'Epic', 'Sprint', 'Priority', 'Story Points', 'Status',
                'Labels', 'Depends On', 'Implementation Spec', 'Description'])
    for sid in order:
        s = stories[sid]
        summary_body = re.sub(r'^# .*\n+', '', s['body'])  # drop the H1, keep story + AC
        w.writerow([sid, f"{sid} {s['title']}", s['type'], s['epic'], milestone_of[sid], s['priority'], s['points'],
                    s['status'], ' '.join(s['labels']), ' '.join(s['depends_on']),
                    s['spec'].replace('../', 'ai-hub/'), summary_body])

print(f'{len(stories)} stories, {total} points → README.md, board.csv')
